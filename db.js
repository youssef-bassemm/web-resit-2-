const sqlite = require('sqlite3');
const db = new sqlite.Database('clinic.db');

const createUserTable = `CREATE TABLE IF NOT EXISTS USER (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  EMAIL TEXT UNIQUE NOT NULL,
  ROLE TEXT NOT NULL DEFAULT 'user',
  PASSWORD TEXT NOT NULL
)`;

const createDoctorTable = `CREATE TABLE IF NOT EXISTS DOCTOR (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  NAME TEXT NOT NULL,
  SPECIALIZATION TEXT NOT NULL,
  AVAILABILITY TEXT DEFAULT 'Mon-Fri 9am-5pm'
)`;

const createAppointmentTable = `CREATE TABLE IF NOT EXISTS APPOINTMENT (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  DOCTOR_ID INTEGER NOT NULL,
  USER_ID INTEGER,
  PATIENT_NAME TEXT NOT NULL,
  APPOINTMENT_DATE TEXT NOT NULL,
  APPOINTMENT_TIME TEXT NOT NULL,
  FOREIGN KEY (DOCTOR_ID) REFERENCES DOCTOR(ID),
  FOREIGN KEY (USER_ID) REFERENCES USER(ID)
)`;

module.exports = {
  db,
  createUserTable,
  createDoctorTable,
  createAppointmentTable,
};
